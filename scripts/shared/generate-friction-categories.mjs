#!/usr/bin/env node
// Regenerate `scripts/shared/friction-categories.generated.mjs` (the friction
// category id list) from the canonical TypeScript source of truth
// (`src/shared/friction/frictionRecord.ts`).
//
// WHY THIS EXISTS. The closeout renderer chain (`scripts/render-closeout.mjs` →
// `scripts/closeout-sections-data.mjs`) must run in a checkout that has NEVER
// been built — the end-of-sprint hand-back is mandatory, and a fresh worktree
// has no `dist/`. Importing `audit-tools/shared` resolves `dist/shared/index.js`
// and dies with ERR_MODULE_NOT_FOUND, which put the mandatory hand-back behind
// `npm install` plus a full `tsc` (backlog 2026-08-29). The renderer chain
// imports THIS generated sibling instead, so the vocabulary keeps exactly one
// hand-maintained home.
//
//   node scripts/shared/generate-friction-categories.mjs           # write
//   node scripts/shared/generate-friction-categories.mjs --check   # verify only
//
// `--check` is wired into verify:checks (check:friction-categories) so a stale
// generated file fails the build rather than silently forking the vocabulary.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { runGeneratedArtifactCli } from "./generatedArtifacts.mjs";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const sourcePath = join(repoRoot, "src", "shared", "friction", "frictionRecord.ts");

/** Pull the id strings out of the canonical `FRICTION_CATEGORIES` literal. */
export function extractFrictionCategories(tsSource) {
  const match = tsSource.match(/export const FRICTION_CATEGORIES = \[([\s\S]*?)\] as const;/);
  if (!match) {
    throw new Error(`could not find the FRICTION_CATEGORIES array literal in ${sourcePath}`);
  }
  // Strip inline comments first: the canonical array carries a `// gloss` per
  // entry, and a quoted word inside one must never become a category.
  const body = match[1].replace(/\/\/[^\n]*/g, "");
  const categories = [...body.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  if (categories.length === 0) {
    throw new Error("FRICTION_CATEGORIES parsed as empty — refusing to generate an empty vocabulary");
  }
  return categories;
}

export function renderFrictionCategoriesModule(categories) {
  return (
    `// @generated by scripts/shared/generate-friction-categories.mjs — DO NOT EDIT.\n` +
    `// Source of truth: src/shared/friction/frictionRecord.ts\n` +
    `//\n` +
    `// The closeout renderer chain runs under plain node in checkouts that may\n` +
    `// have never been built, so it cannot import audit-tools/shared (dist/). It\n` +
    `// imports THIS generated sibling instead. Run the generator after editing\n` +
    `// the source; \`npm run check:friction-categories\` reds while the two differ.\n` +
    `export const FRICTION_CATEGORIES = [\n` +
    categories.map((c) => `  ${JSON.stringify(c)},\n`).join("") +
    `];\n`
  );
}

function main() {
  const categories = extractFrictionCategories(readFileSync(sourcePath, "utf8"));
  runGeneratedArtifactCli({
    repoRoot,
    files: [
      {
        target: "scripts/shared/friction-categories.generated.mjs",
        next: renderFrictionCategoriesModule(categories),
      },
    ],
    staleMessage:
      `The closeout renderer would run against a DIFFERENT friction-category vocabulary than the ` +
      `source of truth, so a hand-back could skip or invent a category.`,
    fixCommand: "node scripts/shared/generate-friction-categories.mjs",
    okMessage: `friction-categories: generated module matches ${categories.length} canonical categor(y/ies)`,
  });
}

// Importable as a library (the parity test exercises the extract + render
// halves directly), so the CLI body runs ONLY on direct invocation — importing
// this module must never write to the tree as a side effect.
const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) main();
