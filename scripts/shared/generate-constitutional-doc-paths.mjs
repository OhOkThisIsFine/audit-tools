#!/usr/bin/env node
// Regenerate `scripts/shared/constitutional-doc-paths.generated.mjs` from the
// canonical TypeScript source of truth (`src/shared/constitutionalDocPaths.ts`).
//
// WHY THIS EXISTS. `.claude/hooks/pre-commit-gate.mjs` runs as a `PreToolUse`
// hook under plain node BEFORE any build, so it genuinely cannot import the TS
// module — but that argues for ONE generated sibling it imports, not a
// hand-kept second copy. Exactly the arrangement
// `scripts/shared/generate-loop-core-patterns.mjs` already gives the loop-core
// list; this is the same rule ("never hand-maintain a table something else can
// generate") applied to the constitutional doc set.
//
// The generated file lives under `scripts/shared/` rather than beside the hook:
// `.gitignore` ignores `.claude/hooks/*` and re-includes each hook BY NAME, so a
// new file there is silently dropped from commits until someone remembers the
// allowlist line. `scripts/` is tracked by default, and both consumers — the
// hook and `scripts/check-doc-manifest.mjs` — import it by relative path.
//
//   node scripts/shared/generate-constitutional-doc-paths.mjs           # write
//   node scripts/shared/generate-constitutional-doc-paths.mjs --check   # verify only
//
// Wire `--check` into verify:checks so a stale generated file fails the build
// rather than silently narrowing the refusal.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const sourcePath = join(repoRoot, "src", "shared", "constitutionalDocPaths.ts");
const outputPath = join(repoRoot, "scripts", "shared", "constitutional-doc-paths.generated.mjs");

/** Pull the string entries out of the canonical `CONSTITUTIONAL_DOC_PATHS` literal. */
export function extractConstitutionalPaths(tsSource) {
  const match = tsSource.match(/export const CONSTITUTIONAL_DOC_PATHS[^=]*=\s*\[([\s\S]*?)\];/);
  if (!match) {
    throw new Error(`could not find the CONSTITUTIONAL_DOC_PATHS array literal in ${sourcePath}`);
  }
  const paths = [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) {
    throw new Error("CONSTITUTIONAL_DOC_PATHS parsed as empty — refusing to generate an empty refusal");
  }
  return paths;
}

export function renderConstitutionalModule(paths) {
  return (
    `// @generated by scripts/shared/generate-constitutional-doc-paths.mjs — DO NOT EDIT.\n` +
    `// Source of truth: src/shared/constitutionalDocPaths.ts\n` +
    `//\n` +
    `// The .claude hooks run under plain node before any build, so they cannot\n` +
    `// import the TypeScript module. They import THIS generated sibling instead,\n` +
    `// so the list has exactly one hand-maintained home. Run the generator (or\n` +
    `// \`npm run check:constitutional-doc-paths\`) after editing the source.\n` +
    `export const CONSTITUTIONAL_DOC_PATHS = [\n` +
    paths.map((p) => `  ${JSON.stringify(p)},\n`).join("") +
    `];\n` +
    `\n` +
    `/** Exact-match membership test; mirrors isConstitutionalDocPath in the TS source. */\n` +
    `export function isConstitutionalDocPath(path) {\n` +
    `  return CONSTITUTIONAL_DOC_PATHS.includes(String(path).replace(/\\\\/g, "/").replace(/^\\.\\//, ""));\n` +
    `}\n`
  );
}

function main() {
  const paths = extractConstitutionalPaths(readFileSync(sourcePath, "utf8"));
  const rendered = renderConstitutionalModule(paths);

  if (process.argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {
      /* missing */
    }
    if (current !== rendered) {
      process.stderr.write(
        `\n${outputPath} is stale or missing.\n` +
          `The constitutional-doc refusal would run against a DIFFERENT path list than the source of truth, ` +
          `which silently narrows or widens which commits are refused.\n` +
          `Fix: node scripts/shared/generate-constitutional-doc-paths.mjs\n\n`,
      );
      process.exit(1);
    }
    process.stdout.write(
      `✓ constitutional-doc-paths: generated list matches ${paths.length} canonical path(s)\n`,
    );
    process.exit(0);
  }

  writeFileSync(outputPath, rendered, "utf8");
  process.stdout.write(`wrote ${outputPath} (${paths.length} paths)\n`);
}

// Importable as a library (the contract test exercises the render directly), so
// the CLI body runs ONLY on direct invocation — importing this module must never
// write to the tree as a side effect.
const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) main();
