#!/usr/bin/env node
// Regenerate `.claude/hooks/loop-core-patterns.mjs` (pattern list + membership
// predicate) from the canonical TypeScript source of truth
// (`src/shared/loopCorePaths.ts`).
//
// WHY THIS EXISTS. The loop-core path list had THREE homes: the TS module plus a
// hand-maintained copy inside each of the two hooks (`pre-commit-gate.mjs`,
// `attest-loop-core-review.mjs`). The hooks run as `PreToolUse` under plain node
// BEFORE any build, so they genuinely cannot import the TS module — but that
// argues for ONE generated sibling they both import, not two hand-kept copies.
// A parity test held the invariant, so nothing ever landed broken; the cost was
// the discovery path. Adding `src/audit/cli/dispatchAttempted.ts` meant editing
// two copies and finding the third only when the parity test went red. The
// property that should hold: ONE edit adds a loop-core path.
//
// The same argument covered the PREDICATE: each hook re-implemented the
// matching logic as a local `pinsLoopCore`, so the SEMANTICS could fork even
// while the list stayed byte-equal. The generated module therefore also emits
// `isLoopCorePath`, mirroring the TS body, and the hooks import it.
//
// This is the project's standing "never hand-maintain a table something else can
// generate" rule applied to our own tree.
//
//   node scripts/shared/generate-loop-core-patterns.mjs           # write
//   node scripts/shared/generate-loop-core-patterns.mjs --check   # verify only
//
// `--check` is wired into verify:checks so a stale generated file fails the
// build rather than silently narrowing the gate.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { runGeneratedArtifactCli } from "./generatedArtifacts.mjs";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const sourcePath = join(repoRoot, "src", "shared", "loopCorePaths.ts");

/**
 * Strip `//` line comments and `/* … *​/` block comments, leaving string
 * literals alone.
 *
 * The array body is REAL TypeScript carrying the prose that justifies each
 * entry, and that prose routinely quotes a phrase — `"written exactly once,
 * logged exactly once"`, a lane id, a rendered sentence. A bare `/"([^"]+)"/g`
 * over the body therefore harvests those phrases as if they were patterns,
 * which is a gate that silently WIDENS with a comment (and, because the
 * generated file is what the hooks import, does so without any test noticing
 * until the byte-parity assertion trips over a phrase nobody meant to add).
 * Scanning the comment-free body is what makes a quoted phrase in a comment
 * inert.
 *
 * Deliberately string-literal-aware rather than regex-only: a `//` INSIDE a
 * pattern string (there is none today, but a URL-shaped path would have one)
 * must not be read as the start of a comment and truncate the list.
 */
function stripComments(source) {
  let out = "";
  let i = 0;
  let quote = null;
  while (i < source.length) {
    const ch = source[i];
    const next = source[i + 1];
    if (quote !== null) {
      out += ch;
      if (ch === "\\") {
        out += next ?? "";
        i += 2;
        continue;
      }
      if (ch === quote) quote = null;
      i += 1;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      quote = ch;
      out += ch;
      i += 1;
      continue;
    }
    if (ch === "/" && next === "/") {
      while (i < source.length && source[i] !== "\n") i += 1;
      continue;
    }
    if (ch === "/" && next === "*") {
      i += 2;
      while (i < source.length && !(source[i] === "*" && source[i + 1] === "/")) i += 1;
      i += 2;
      continue;
    }
    out += ch;
    i += 1;
  }
  return out;
}

/** Pull the string entries out of the canonical `LOOP_CORE_PATTERNS` literal. */
export function extractPatterns(tsSource) {
  const match = tsSource.match(/export const LOOP_CORE_PATTERNS[^=]*=\s*\[([\s\S]*?)\];/);
  if (!match) {
    throw new Error(`could not find the LOOP_CORE_PATTERNS array literal in ${sourcePath}`);
  }
  const patterns = [...stripComments(match[1]).matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  if (patterns.length === 0) {
    throw new Error("LOOP_CORE_PATTERNS parsed as empty — refusing to generate an empty gate");
  }
  return patterns;
}

export function renderModule(patterns) {
  return (
    `// @generated by scripts/shared/generate-loop-core-patterns.mjs — DO NOT EDIT.\n` +
    `// Source of truth: src/shared/loopCorePaths.ts\n` +
    `//\n` +
    `// The .claude hooks run under plain node before any build, so they cannot\n` +
    `// import the TypeScript module. They import THIS generated sibling instead,\n` +
    `// so the list and its membership predicate have exactly one hand-maintained\n` +
    `// home. Run the generator (or \`npm run check:loop-core-patterns\`) after\n` +
    `// editing the source.\n` +
    `export const LOOP_CORE_PATTERNS = [\n` +
    patterns.map((p) => `  ${JSON.stringify(p)},\n`).join("") +
    `];\n` +
    `\n` +
    `/** Whether a repo-relative path is in the loop-core set; mirrors isLoopCorePath\n` +
    ` * in the TS source: normalize backslashes + a leading "./"; a "/"-terminated\n` +
    ` * pattern matches the directory prefix, else exact match. */\n` +
    `export function isLoopCorePath(path) {\n` +
    `  const p = String(path).replace(/\\\\/g, "/").replace(/^\\.\\//, "");\n` +
    `  for (const pattern of LOOP_CORE_PATTERNS) {\n` +
    `    if (pattern.endsWith("/")) {\n` +
    `      if (p.startsWith(pattern)) return true;\n` +
    `    } else if (p === pattern) {\n` +
    `      return true;\n` +
    `    }\n` +
    `  }\n` +
    `  return false;\n` +
    `}\n`
  );
}

function main() {
  const patterns = extractPatterns(readFileSync(sourcePath, "utf8"));
  runGeneratedArtifactCli({
    repoRoot,
    files: [{ target: ".claude/hooks/loop-core-patterns.mjs", next: renderModule(patterns) }],
    staleMessage:
      `The loop-core gate would run against a DIFFERENT path list or predicate than the source of ` +
      `truth, which silently narrows or widens which commits require review attestation.`,
    fixCommand: "node scripts/shared/generate-loop-core-patterns.mjs",
    okMessage: `loop-core-patterns: generated hook module matches ${patterns.length} canonical pattern(s) + predicate`,
  });
}

// Importable as a library (the parity test exercises `renderModule` directly),
// so the CLI body runs ONLY on direct invocation — importing this module must
// never write to the tree as a side effect.
const invokedDirectly =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;

if (invokedDirectly) main();
