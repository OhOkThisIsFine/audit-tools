#!/usr/bin/env node
// README sample-report reconciliation gate (docs-4, nightly 2026-08-25).
//
// The README's sample audit-report block used to be hand-typed and showed
// headings the renderer never emits. It is now GENERATED: the same substrate
// `audit-code sample-run` persists (buildSampleAuditBundle) is rendered
// through the real renderer with one typed fixture finding
// (SAMPLE_REPORT_FINDING), and the README block is an excerpt of that output
// — so the sample cannot drift from the renderer again.
//
// Usage (tsx loader required — the bundle builder is TypeScript source):
//   node --import tsx/esm scripts/check-readme-sample-report.mjs           # verify (exit 1 on drift)
//   node --import tsx/esm scripts/check-readme-sample-report.mjs --write   # regenerate the README block
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  SAMPLE_REPORT_FINDING,
  buildSampleAuditBundle,
} from '../src/audit/cli/sampleRunCommand.ts';

const ROOT = process.env.CLAUDE_PROJECT_DIR || process.cwd();
const TARGET = 'README.md';

export const README_BEGIN =
  '<!-- BEGIN sample-report — generated by scripts/check-readme-sample-report.mjs from the real renderer; do not hand-edit -->';
export const README_END = '<!-- END sample-report -->';

/** Slice one `## `-headed section (heading included) out of the rendered report. */
export function sliceSection(lines, heading) {
  const start = lines.indexOf(heading);
  if (start === -1) {
    throw new Error(
      `the rendered report lost its '${heading}' heading — update the excerpt in scripts/check-readme-sample-report.mjs to match the renderer`,
    );
  }
  let end = start + 1;
  while (end < lines.length && !lines[end].startsWith('## ')) end += 1;
  return lines.slice(start, end);
}

/**
 * The excerpt: H1 + Summary + Findings (one fixture finding). Every line is a
 * verbatim renderer line; a renderer heading change reds this gate instead of
 * silently drifting the README.
 */
export async function renderSampleExcerpt() {
  const { auditReport } = await buildSampleAuditBundle([SAMPLE_REPORT_FINDING]);
  const lines = auditReport.split('\n');
  const h1 = lines.indexOf('# Audit Report');
  if (h1 === -1) {
    throw new Error(
      "the rendered report lost its '# Audit Report' H1 — update the excerpt in scripts/check-readme-sample-report.mjs to match the renderer",
    );
  }
  const excerpt = [
    lines[h1],
    '',
    ...sliceSection(lines, '## Summary'),
    ...sliceSection(lines, '## Findings'),
  ];
  while (excerpt.length > 0 && excerpt[excerpt.length - 1].trim() === '') excerpt.pop();
  // Backticks are stripped: inside the README's ```text fence they would
  // display as literal characters, and a backticked fabricated path would trip
  // check:doc-code-citations, whose declared scope is backticked citations.
  return excerpt.map((line) => line.replaceAll('`', '')).join('\n');
}

/** The exact README block, markers included. */
export async function renderReadmeBlock() {
  return [
    README_BEGIN,
    '',
    '*(Illustrative excerpt — rendered by the real report renderer from a fabricated sample repo and one fixture finding; the cited src/api/auth.ts path belongs to that fabricated repo, not to this repository. A real report carries more sections between Summary and Findings.)*',
    '',
    '```text',
    await renderSampleExcerpt(),
    '```',
    '',
    README_END,
  ].join('\n');
}

/** Replace the README's marked block. Pure — returns the new file text. */
export async function applyToReadme(readmeText) {
  const begin = readmeText.indexOf(README_BEGIN);
  const end = readmeText.indexOf(README_END);
  if (begin === -1 || end === -1 || end < begin) {
    throw new Error(
      `${TARGET} is missing the sample-report markers:\n${README_BEGIN}\n${README_END}`,
    );
  }
  return (
    readmeText.slice(0, begin) +
    (await renderReadmeBlock()) +
    readmeText.slice(end + README_END.length)
  );
}

// ── CLI ──────────────────────────────────────────────────────────────────────
// Only when run directly; importing for tests must not execute the gate.
const invokedDirectly =
  process.argv[1] && process.argv[1].endsWith('check-readme-sample-report.mjs');
if (invokedDirectly) {
  const write = process.argv.includes('--write');
  try {
    const readmePath = join(ROOT, TARGET);
    const readme = readFileSync(readmePath, 'utf8');
    const next = await applyToReadme(readme);

    if (write) {
      if (next !== readme) writeFileSync(readmePath, next);
      console.log(`✓ readme-sample-report: ${TARGET} regenerated from the renderer.`);
      process.exit(0);
    }

    if (next !== readme) {
      console.error(
        `✗ readme-sample-report check failed: ${TARGET}'s sample block does not match the renderer's output.\n` +
          '  The block is GENERATED — regenerate: npm run check:readme-sample-report -- --write',
      );
      process.exit(1);
    }
    console.log(`✓ readme-sample-report: ${TARGET}'s sample block matches the renderer.`);
  } catch (err) {
    console.error(`✗ readme-sample-report check failed: ${/** @type {any} */ (err).message}`);
    process.exit(1);
  }
}
